"""Step C2: write configs/captures.yaml from ROAD's own metadata files.

Signal CSVs are taken ONLY from signal_extractions/attacks for attacks; the
signal_extractions/ambient folder also contains copies of attack CSVs
(accelerator + masquerade), which must never be treated as ambient.
"""
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
R = ROOT / "data/raw/road/road"


def family(name):
    if name.startswith("accelerator"):
        return "accelerator"
    if name.startswith("fuzzing"):
        return "fuzzing"
    return "masquerade" if name.endswith("_masquerade") else "fabrication"


def main():
    amb_meta = json.load(open(R / "ambient/capture_metadata.json"))
    att_meta = json.load(open(R / "attacks/capture_metadata.json"))
    ambient = []
    for name, m in sorted(amb_meta.items()):
        sig = R / "signal_extractions/ambient" / f"{name}.csv"
        ambient.append({"name": name, "kind": "ambient", "family": "ambient",
                        "path": str((R / "ambient" / f"{name}.log").relative_to(ROOT)),
                        "signal_path": str(sig.relative_to(ROOT)) if sig.exists() else None,
                        "elapsed_sec": m["elapsed_sec"], "on_dyno": m["on_dyno"]})
    attacks = []
    for name, m in sorted(att_meta.items()):
        fam = family(name)
        sig = R / "signal_extractions/attacks" / f"{name}.csv"
        atype = name.replace("_masquerade", "")
        atype = atype.rsplit("_", 1)[0] if atype[-1].isdigit() else atype
        pair = (name[: -len("_masquerade")] if fam == "masquerade"
                else f"{name}_masquerade" if f"{name}_masquerade" in att_meta else None)
        inj = m["injection_id"]
        attacks.append({
            "name": name, "kind": "attack", "family": fam, "attack_type": atype,
            "path": str((R / "attacks" / f"{name}.log").relative_to(ROOT)),
            "signal_path": str(sig.relative_to(ROOT)) if sig.exists() else None,
            "pair_with": pair,
            "target_aid": int(inj, 16) if inj and inj != "XXX" else None,
            "injection_data": m["injection_data_str"],
            "interval_start_s": m["injection_interval"][0] if m["injection_interval"] else None,
            "interval_end_s": m["injection_interval"][1] if m["injection_interval"] else None,
            "elapsed_sec": m["elapsed_sec"]})
    for c in ambient + attacks:
        for k in ("path", "signal_path"):
            assert c[k] is None or (ROOT / c[k]).exists(), c[k]
    out = {"root": "data/raw/road/road", "ambient": ambient, "attacks": attacks}
    with open(ROOT / "configs/captures.yaml", "w") as fh:
        fh.write("# GENERATED by src/build_inventory.py from ROAD capture_metadata.json files.\n")
        yaml.safe_dump(out, fh, sort_keys=False, width=200)
    fams = {}
    for a in attacks:
        fams[a["family"]] = fams.get(a["family"], 0) + 1
    print(f"ambient={len(ambient)} attacks={len(attacks)} {fams}")
    print("with signals:", sum(c['signal_path'] is not None for c in attacks), "attacks,",
          sum(c['signal_path'] is not None for c in ambient), "ambient")


if __name__ == "__main__":
    main()
