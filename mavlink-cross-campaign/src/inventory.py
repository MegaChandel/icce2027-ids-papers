"""Capture inventory for the three MAVLink campaigns -> configs/data.yaml, and parquet cache.

Labels are per FILE in all three corpora (see README, Step C2).
Only frames from the vehicle (sysid 1, compid 1) are kept: the HCRL "(filtered)" files and
the OLD files already contain only these; the unfiltered NEW files are not used.
"""
from __future__ import annotations

import pathlib
import re
from multiprocessing import Pool

import pandas as pd
import yaml

from .io_mavlink import load_pcap

ROOT = pathlib.Path(__file__).resolve().parents[1]
RAW, INTERIM = ROOT / "data/raw", ROOT / "data/interim"


def build() -> dict:
    caps = []
    for p in sorted((RAW / "msgid/pcap").glob("hitl_100000_*.pcapng")):
        m = re.match(r"hitl_100000_([a-z]+?)(2?)\.pcapng", p.name)
        kind, rep = m.group(1), 2 if m.group(2) else 1
        caps.append(dict(name=f"old_{kind}_{rep}", campaign="OLD", attack=kind,
                         label=int(kind != "normal"), scenario="hitl", rep=rep,
                         path=str(p.relative_to(ROOT))))
    for p in sorted((RAW / "msgid/pcap").glob("*(filtered).pcapng")):
        kind = p.name.split("(")[0]
        caps.append(dict(name=f"new_{kind}_1", campaign="NEW", attack=kind,
                         label=int(kind != "normal"), scenario="hitl", rep=1,
                         path=str(p.relative_to(ROOT))))
    for p in sorted((RAW / "shadow").glob("*.pcapng")):
        mode, state, cls, rep = p.stem.split("-")
        caps.append(dict(name=f"shadow_{mode}_{state}_{cls}_{rep}".lower(), campaign="SHADOW",
                         attack="relay" if cls == "Attack" else "normal", label=int(cls == "Attack"),
                         scenario=f"{mode}-{state}".lower(), rep=int(rep), path=str(p.relative_to(ROOT))))
    cfg = {"captures": caps}
    with open(ROOT / "configs/data.yaml", "w") as fh:
        fh.write("# GENERATED by src/inventory.py. Labels are per file.\n")
        yaml.safe_dump(cfg, fh, sort_keys=False, width=200)
    return cfg


def _cache_one(c: dict) -> str:
    df = load_pcap(ROOT / c["path"])
    df = df[(df.sysid == 1) & (df.compid == 1)].reset_index(drop=True)
    df["t"] -= df["t"].iloc[0]
    df.to_parquet(INTERIM / f"{c['name']}.parquet", index=False)
    return f"{c['name']}: {len(df)} frames, {df.t.max():.0f}s, {df.msgid.nunique()} ids"


def cache(cfg, processes: int = 12) -> None:
    INTERIM.mkdir(parents=True, exist_ok=True)
    with Pool(processes) as pool:
        for msg in pool.imap_unordered(_cache_one, cfg["captures"]):
            print(msg, flush=True)


def load_cfg() -> dict:
    with open(ROOT / "configs/data.yaml") as fh:
        return yaml.safe_load(fh)


def load(name: str) -> pd.DataFrame:
    return pd.read_parquet(INTERIM / f"{name}.parquet")


if __name__ == "__main__":
    cfg = build()
    print(pd.DataFrame(cfg["captures"]).groupby(["campaign", "attack"]).size().to_string())
    cache(cfg)
